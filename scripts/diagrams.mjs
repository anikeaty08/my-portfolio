// Excalidraw scenes in scripts/*.excalidraw are the editable diagram sources.
// This script records dimensions of their SVG exports for stable article layout.
import fs from "node:fs";
import path from "node:path";

const article = fs.readFileSync("src/data/rag-article.src.md", "utf8");
const names = [...article.matchAll(/!\[[^\]]*\]\(\/articles\/([^\s)]+\.svg)\)/g)].map((match) => match[1]);
const sizes = {};

for (const name of new Set(names)) {
  const source = path.join("scripts", name.replace(/\.svg$/, ".excalidraw"));
  const image = path.join("public", "articles", name);
  if (!fs.existsSync(source)) throw new Error(`Missing Excalidraw source: ${source}`);
  if (!fs.existsSync(image)) throw new Error(`Missing SVG export: ${image}`);
  const svg = fs.readFileSync(image, "utf8");
  const viewBox = svg.match(/viewBox="[\d.\-]+\s+[\d.\-]+\s+([\d.]+)\s+([\d.]+)"/);
  if (!viewBox) throw new Error(`Missing SVG viewBox: ${image}`);
  sizes[`/articles/${name}`] = [Math.ceil(Number(viewBox[1])), Math.ceil(Number(viewBox[2]))];
}

fs.writeFileSync(
  "src/data/diagram-sizes.ts",
  "// Generated by scripts/diagrams.mjs from Excalidraw SVG exports.\n" +
    `export const diagramSizes: Record<string, [number, number]> = ${JSON.stringify(sizes, null, 2)};\n`,
);
console.log(`Recorded dimensions for ${Object.keys(sizes).length} Excalidraw diagrams.`);
